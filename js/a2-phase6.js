/* Phase 6 integration: preserve prior progress and completed daily activities. */
const A2Phase6 = {
  version:6,
  install(){
    if(this.installed)return;this.installed=true;
    // Keep the existing Studio as a navigation page. Conversation buttons launch Worker roleplay.
    const oldStudio=A2Studio.render;
    A2Studio.render=function(...args){
      const out=oldStudio.apply(this,args);
      const root=document.getElementById('a2StudioContent');
      const chats=root?.querySelector('#studioChats');
      if(chats){
        chats.querySelectorAll('[data-scenario]').forEach(b=>b.onclick=()=>A2AIConversation.open(b.dataset.scenario));
        const note=chats.parentElement.querySelector('p');if(note)note.textContent='AI-powered, multi-turn Dutch conversations. The Worker asks new follow-up questions based on your answers; microphone and typed responses are supported.';
      }
      const exams=root?.querySelector('#studioExams');
      if(exams){
        const note=exams.parentElement.querySelector('p');if(note)note.textContent='Optional reading/listening samplers. For fresh Worker-generated practice, use the buttons below.';
        const div=document.createElement('div');div.className='a2-actions';
        ['reading','listening','writing','speaking'].forEach(skill=>{
          const btn=document.createElement('button');btn.textContent=`New AI ${skill} practice →`;btn.onclick=()=>A2Phase6.startSkill(skill);div.append(btn);
        });exams.parentElement.append(div);
      }
      return out;
    };
    // Phase 5 continues handling daily completion, but launches new Worker conversations.
    const oldLaunch=A2AdaptivePhase5.launch;
    A2AdaptivePhase5.launch=function(activity){
      if(activity.studioKind==='conversation'){
        this.currentTask={date:this.dateKey(),id:activity.id,kind:'conversation',studioId:activity.studioId};
        A2AIConversation.open(activity.studioId);return;
      }
      return oldLaunch.call(this,activity);
    };
    // All NEW daily plans start from the existing scheduler, then prefer one lesson,
    // one weakness/review and diversified skill practice. Existing completed slots are untouched.
    const oldDecorate=A2AdaptivePhase5.decorate;
    A2AdaptivePhase5.decorate=function(plan,date,completed){
      const result=oldDecorate.call(this,plan,date,completed);
      if(!result?.activities?.length)return result;
      const slots=result.activities;
      const next=CurriculumEngine.nextLesson('A2');
      if(next&&!slots.some(a=>a.studioKind==='lesson')){
        const slot=slots.find(a=>!completed?.[a.id]&&a.type==='skill')||slots.find(a=>!completed?.[a.id]&&a.studioKind==='assessment');
        if(slot)Object.assign(slot,{type:'a2_studio',source:'a2_studio',studioKind:'lesson',studioId:next.id,title:`New lesson: ${next.title}`,subtitle:'Structured A2 curriculum',level:'A2',icon:'📘'});
      }
      // Do not offer two generic vocabulary slots on the same day.
      let seenVocabulary=false;
      for(const a of slots){
        if(a.skill!=='vocabulary'&&a.studioKind!=='vocabulary')continue;
        if(!seenVocabulary){seenVocabulary=true;continue;}
        if(completed?.[a.id])continue;
        if(a.type==='a2_studio'&&a.studioKind==='vocabulary'){
          Object.assign(a,{type:'skill',source:'phase6',skill:'reading',title:'Reading',subtitle:'Fresh AI-generated A2 reading',level:'A2'});
          delete a.studioKind;delete a.studioId;
        }else if(a.type==='skill'){Object.assign(a,{skill:'reading',title:'Reading',subtitle:'Fresh AI-generated A2 reading',level:'A2'});}
      }
      return result;
    };
    A2AdaptivePhase5.version=6;
    // Lesson content stays curated; practice questions are generated by the Worker.
    const oldLesson=CurriculumEngine.openLesson;
    CurriculumEngine.openLesson=function(id){
      oldLesson.call(this,id);
      const root=document.getElementById('curriculum');
      const button=root?.querySelector('#curriculumPractice');
      if(button)button.textContent='Generate new AI questions for this lesson →';
    };
  },
  startSkill(skill){
    Dashboard.activeActivity=null;
    return PracticeUI.startFromActivity({id:`phase6-${skill}-${Date.now()}`,type:'skill',skill,level:'A2',minutes:15,source:'phase6',title:`A2 ${skill}`});
  }
};
A2Phase6.install();
