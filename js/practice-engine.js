/*
==================================================
MIJN NEDERLANDS
PRACTICE ENGINE
==================================================

Creates personalized practice sessions from
the learner's current profile and study plan.

This engine is for LEARNING/PRACTICE.

It is deliberately separate from:
- placement assessment
- writing assessment
- speaking assessment
==================================================
*/


const PracticeEngine = {

  /*
  ==================================================
  SESSION CREATION
  ==================================================
  */

  createConceptSession(
    concept,
    profile,
    options = {}
  ) {

    const normalizedConcept =
      String(concept || "")
        .trim()
        .toLowerCase();


    if (!normalizedConcept) {

      throw new Error(
        "PracticeEngine requires a concept."
      );

    }


    const minutes =
      Number.isFinite(
        options.minutes
      )
        ? options.minutes
        : 10;


    const level =
      this.getPracticeLevel(
        profile,
        normalizedConcept
      );


    const weakness =
      this.findWeakness(
        profile,
        normalizedConcept
      );


    return {

      id:
        this.createSessionId(
          normalizedConcept
        ),


      /*
      ------------------------------------------
      PRACTICE MODE
      ------------------------------------------

      Keep type for backward compatibility.

      practiceType is the new explicit contract
      shared by:

      - PracticeEngine
      - PracticeUI
      - MijnNederlandsAPI
      - Worker
      ------------------------------------------
      */

      type:
        "concept_practice",

      practiceType:
        "concept",


      /*
      Concept practice targets a specific
      learner concept.

      skill remains null so that skill names
      never accidentally become concepts.
      */

      concept:
        normalizedConcept,

      skill:
        null,


      title:
        this.formatConcept(
          normalizedConcept
        ),


      level,

      minutes,


      createdAt:
        new Date()
          .toISOString(),


      status:
        "ready",


      source:
        weakness
          ? "learner_profile"
          : "study_plan",


      weakness:
        weakness ||
        null,


      activities:
        this.createConceptActivities(
          normalizedConcept,
          level,
          weakness,
          minutes
        )

    };

  },


  /*
  ==================================================
  SKILL SESSION CREATION
  ==================================================

  Skill practice is different from concept
  remediation.

  Examples:

      reading
      writing
      grammar
      vocabulary

  These must NOT be stored as fake concepts such
  as:

      concept: "reading"

  Instead the session explicitly identifies
  itself as skill practice.
  ==================================================
  */

  createSkillSession(
    skill,
    profile,
    options = {}
  ) {

    const normalizedSkill =
      String(skill || "")
        .trim()
        .toLowerCase();


    const supportedSkills = [

      "grammar",

      "vocabulary",

      "reading",

      "listening",

      "writing",

      "speaking"

    ];


    if (
      !supportedSkills.includes(
        normalizedSkill
      )
    ) {

      throw new Error(
        "PracticeEngine requires a supported skill."
      );

    }


    const minutes =
      Number.isFinite(
        options.minutes
      )
        ? options.minutes
        : 10;


    const level =
      this.getSkillPracticeLevel(
        profile,
        normalizedSkill
      );


    return {

      id:
        this.createSessionId(
          `skill_${normalizedSkill}`
        ),


      type:
        "skill_practice",

      practiceType:
        "skill",


      /*
      ------------------------------------------
      IMPORTANT
      ------------------------------------------

      A skill-practice session has no concept.

      This prevents:

          reading
          writing
          grammar
          vocabulary

      from being inserted into the concept
      mastery/discovery system.
      ------------------------------------------
      */

      concept:
        null,

      skill:
        normalizedSkill,


      title:
        `${this.formatConcept(
          normalizedSkill
        )} practice`,


      level,

      minutes,


      createdAt:
        new Date()
          .toISOString(),


      status:
        "ready",


      source:
        "study_plan",


      weakness:
        null,


      /*
      The actual exercises for skill practice
      are generated by the Worker.

      We intentionally do not create fake
      concept activities here.
      */

      activities: []

    };

  },


  /*
  ==================================================
  CONCEPT ACTIVITY GENERATION
  ==================================================
  */

  createConceptActivities(
    concept,
    level,
    weakness,
    minutes
  ) {

    /*
    This creates the structural stages of a
    concept-practice session.

    The Worker later generates the real lesson
    and exercises.
    */

    const activities = [];


    /*
    ------------------------------------------
    LEARN
    ------------------------------------------
    */

    activities.push({

      id:
        `${concept}_learn`,

      type:
        "explanation",

      concept,

      level,

      minutes:
        Math.min(
          2,
          minutes
        ),

      title:
        `Learn ${
          this.formatConcept(
            concept
          )
        }`

    });


    /*
    ------------------------------------------
    GUIDED PRACTICE
    ------------------------------------------
    */

    activities.push({

      id:
        `${concept}_guided`,

      type:
        "guided_practice",

      concept,

      level,

      minutes:
        Math.max(
          2,
          Math.round(
            minutes * 0.4
          )
        ),

      title:
        "Guided practice"

    });


    /*
    ------------------------------------------
    INDEPENDENT PRACTICE
    ------------------------------------------
    */

    activities.push({

      id:
        `${concept}_independent`,

      type:
        "independent_practice",

      concept,

      level,

      minutes:
        Math.max(
          2,
          minutes -
          activities.reduce(
            (
              sum,
              activity
            ) =>
              sum +
              activity.minutes,
            0
          )
        ),

      title:
        "Try it yourself"

    });


    return activities;

  },


  /*
  ==================================================
  CONCEPT PRACTICE LEVEL
  ==================================================
  */

  getPracticeLevel(
  profile,
  concept
) {

  /*
  ==================================================
  NORMALIZE CONCEPT
  ==================================================

  Concept practice should start from the skill
  most closely related to the concept.

  Examples:

    vocabulary_choice
      -> vocabulary

    spelling
      -> writing

    perfect_tense
      -> grammar / writing

    word_order
      -> grammar / writing

  This prevents vocabulary remediation from
  accidentally inheriting the learner's
  writing level.
  ==================================================
  */

  const conceptName =
    String(
      concept || ""
    )
      .trim()
      .toLowerCase();


  const skills =
    profile?.skills ||
    {};


  /*
  ==================================================
  HELPER
  ==================================================
  */

  const getAssessedLevel =
    skillName => {

      const skill =
        skills[
          skillName
        ];


      if (
        skill?.assessed &&
        skill.level
      ) {

        return skill.level;

      }


      return null;

    };


  /*
  ==================================================
  VOCABULARY CONCEPTS
  ==================================================
  */

  const vocabularySignals = [

    "vocabulary",

    "word_choice",

    "word_meaning",

    "lexical",

    "woordenschat"

  ];


  if (
    vocabularySignals.some(
      signal =>
        conceptName.includes(
          signal
        )
    )
  ) {

    const vocabularyLevel =
      getAssessedLevel(
        "vocabulary"
      );


    if (vocabularyLevel) {

      return vocabularyLevel;

    }

  }


  /*
  ==================================================
  SPELLING / WRITING CONCEPTS
  ==================================================
  */

  const writingSignals = [

    "spelling",

    "orthography",

    "punctuation",

    "capitalization"

  ];


  if (
    writingSignals.some(
      signal =>
        conceptName.includes(
          signal
        )
    )
  ) {

    const writingLevel =
      getAssessedLevel(
        "writing"
      );


    if (writingLevel) {

      return writingLevel;

    }

  }


  /*
  ==================================================
  GRAMMAR CONCEPTS
  ==================================================

  Grammar concepts prefer the assessed grammar
  level.

  Writing remains a fallback because many of
  these concepts are discovered through
  productive writing/speaking evidence.
  ==================================================
  */

  const grammarSignals = [

    "tense",

    "perfect",

    "past",

    "present",

    "future",

    "modal",

    "verb",

    "conjugation",

    "word_order",

    "article",

    "adjective",

    "pronoun",

    "preposition",

    "plural",

    "grammar"

  ];


  if (
    grammarSignals.some(
      signal =>
        conceptName.includes(
          signal
        )
    )
  ) {

    const grammarLevel =
      getAssessedLevel(
        "grammar"
      );


    if (grammarLevel) {

      return grammarLevel;

    }


    const writingLevel =
      getAssessedLevel(
        "writing"
      );


    if (writingLevel) {

      return writingLevel;

    }

  }


  /*
  ==================================================
  UNKNOWN CONCEPT FALLBACK
  ==================================================

  Preserve the existing behavior for concepts
  that we have not classified yet.

  This avoids unexpectedly changing the level
  of every existing concept.
  ==================================================
  */

  const writingLevel =
    getAssessedLevel(
      "writing"
    );


  if (writingLevel) {

    return writingLevel;

  }


  const grammarLevel =
    getAssessedLevel(
      "grammar"
    );


  if (grammarLevel) {

    return grammarLevel;

  }


  return "A1";

},


  /*
  ==================================================
  SKILL PRACTICE LEVEL
  ==================================================

  For skill practice, prefer the learner's
  assessed level for that exact skill.

  Example:

      Reading practice
      -> reading level

      Writing practice
      -> writing level

  If that skill has not been assessed, use a
  sensible assessed fallback rather than blocking
  practice entirely.
  ==================================================
  */

  getSkillPracticeLevel(
  profile,
  skill
) {

  /*
  ==================================================
  NORMALIZE SKILL
  ==================================================
  */

  const normalizedSkill =
    String(skill || "")
      .trim()
      .toLowerCase();


  /*
  ==================================================
  CEFR LEVELS
  ==================================================

  Practice currently supports:

      A1 → A2 → B1

  Adaptive movement is deliberately limited
  to ONE step at a time.
  ==================================================
  */

  const levels = [
    "A1",
    "A2",
    "B1"
  ];


  /*
  ==================================================
  FIND ASSESSED BASE LEVEL
  ==================================================

  The assessment/profile remains the source
  of the learner's official estimated level.

  Adaptive practice NEVER overwrites this.
  ==================================================
  */

  const skillProfile =
    profile
      ?.skills
      ?.[normalizedSkill];


  let assessedLevel =
    null;


  if (
    skillProfile?.assessed &&
    skillProfile.level &&
    levels.includes(
      String(
        skillProfile.level
      ).toUpperCase()
    )
  ) {

    assessedLevel =
      String(
        skillProfile.level
      ).toUpperCase();

  }


  /*
  ==================================================
  FALLBACK LEVEL
  ==================================================

  If this exact skill has not been assessed,
  use other assessed language evidence.

  A1 remains the final safe fallback.
  ==================================================
  */

  if (!assessedLevel) {

    const fallbackSkills = [

      "grammar",

      "writing",

      "reading",

      "vocabulary"

    ];


    for (
      const fallbackSkill
      of fallbackSkills
    ) {

      const fallback =
        profile
          ?.skills
          ?.[fallbackSkill];


      const fallbackLevel =
        String(
          fallback?.level || ""
        ).toUpperCase();


      if (
        fallback?.assessed &&
        levels.includes(
          fallbackLevel
        )
      ) {

        assessedLevel =
          fallbackLevel;

        break;

      }

    }

  }


  if (!assessedLevel) {

    assessedLevel =
      "A1";

  }


  /*
  ==================================================
  LOAD PRACTICE HISTORY
  ==================================================

  Older concept-practice records do not have
  practiceType or skill.

  They are intentionally ignored here.
  ==================================================
  */

  let history = [];


  try {

    if (
      typeof Storage !==
        "undefined" &&
      typeof Storage
        .getPracticeHistory ===
        "function"
    ) {

      const storedHistory =
        Storage
          .getPracticeHistory();


      if (
        Array.isArray(
          storedHistory
        )
      ) {

        history =
          storedHistory;

      }

    }

  } catch (error) {

    console.warn(
      "Could not load practice history for adaptive level:",
      error
    );


    return assessedLevel;

  }


  /*
  ==================================================
  FIND THIS SKILL'S PRACTICE
  ==================================================

  Only genuine skill-practice sessions count.

  Concept practice must never change the
  learner's Reading/Writing/etc. practice level.
  ==================================================
  */

  const skillHistory =
    history
      .filter(
        result => {

          if (!result) {
            return false;
          }


          const resultSkill =
            String(
              result.skill || ""
            )
              .trim()
              .toLowerCase();


          const resultType =
            String(
              result.practiceType ||
              result.type ||
              ""
            )
              .trim()
              .toLowerCase();


          const isSkillPractice =
            resultType ===
              "skill" ||
            resultType ===
              "skill_practice";


          return (
            isSkillPractice &&
            resultSkill ===
              normalizedSkill
          );

        }
      )
      .map(
        result => {

          /*
          ------------------------------------------
          NORMALIZE SCORE
          ------------------------------------------
          */

          let score =
            Number(
              result.score
            );


          if (
            !Number.isFinite(
              score
            )
          ) {

            const correct =
              Number(
                result.correct
              );


            const total =
              Number(
                result.total
              );


            if (
              Number.isFinite(
                correct
              ) &&
              Number.isFinite(
                total
              ) &&
              total > 0
            ) {

              score =
                Math.round(
                  (
                    correct /
                    total
                  ) * 100
                );

            }

          }


          const level =
            String(
              result.level || ""
            ).toUpperCase();


          const time =
            new Date(
              result.completedAt ||
              result.savedAt ||
              result.createdAt ||
              0
            ).getTime();


          return {

            ...result,

            adaptiveScore:
              score,

            adaptiveLevel:
              level,

            adaptiveTime:
              Number.isFinite(time)
                ? time
                : 0

          };

        }
      )
      .filter(
        result =>
          Number.isFinite(
            result.adaptiveScore
          ) &&
          levels.includes(
            result.adaptiveLevel
          )
      )
      .sort(
        (a, b) =>
          b.adaptiveTime -
          a.adaptiveTime
      );


  /*
  ==================================================
  NOT ENOUGH EVIDENCE
  ==================================================

  Never adapt from a single session.
  ==================================================
  */

  if (
    skillHistory.length < 2
  ) {

    return assessedLevel;

  }


  /*
  ==================================================
  DETERMINE CURRENT PRACTICE LEVEL
  ==================================================

  The most recent skill-practice session tells
  us which level the learner has actually been
  practising.

  This is important after a previous adaptive
  downgrade.

  Example:

      assessment = B1
      practice    = A2

  We need to evaluate recent A2 evidence rather
  than immediately resetting to B1.
  ==================================================
  */

  const mostRecentLevel =
    skillHistory[0]
      .adaptiveLevel;


  const currentPracticeLevel =
    levels.includes(
      mostRecentLevel
    )
      ? mostRecentLevel
      : assessedLevel;


  /*
  ==================================================
  SAME-LEVEL RECENT EVIDENCE
  ==================================================

  Only compare sessions completed at the current
  practice level.

  Mixing A2 and B1 scores would make the adaptive
  decision misleading.
  ==================================================
  */

  const sameLevelHistory =
    skillHistory
      .filter(
        result =>
          result.adaptiveLevel ===
          currentPracticeLevel
      )
      .slice(
        0,
        3
      );


  /*
  We require at least two sessions at the same
  level before changing difficulty.
  */

  if (
    sameLevelHistory.length < 2
  ) {

    return currentPracticeLevel;

  }


  /*
  ==================================================
  WEIGHT RECENT RESULTS
  ==================================================

  Most recent session matters slightly more.

  With three sessions:

      newest = 50%
      middle = 30%
      oldest = 20%

  With two sessions:

      newest = 60%
      previous = 40%
  ==================================================
  */

  let weightedScore;


  if (
    sameLevelHistory.length >= 3
  ) {

    weightedScore =
      (
        sameLevelHistory[0]
          .adaptiveScore *
        0.5
      ) +
      (
        sameLevelHistory[1]
          .adaptiveScore *
        0.3
      ) +
      (
        sameLevelHistory[2]
          .adaptiveScore *
        0.2
      );

  } else {

    weightedScore =
      (
        sameLevelHistory[0]
          .adaptiveScore *
        0.6
      ) +
      (
        sameLevelHistory[1]
          .adaptiveScore *
        0.4
      );

  }


  weightedScore =
    Math.round(
      weightedScore
    );


  /*
  ==================================================
  CONSISTENCY CHECKS
  ==================================================

  One unusually good or bad session should not
  change the learner's practice level.
  ==================================================
  */

  const consistentlyStruggling =
    sameLevelHistory
      .every(
        result =>
          result.adaptiveScore <
          55
      );


  const consistentlyStrong =
    sameLevelHistory
      .every(
        result =>
          result.adaptiveScore >=
          85
      );


  /*
  ==================================================
  CURRENT LEVEL INDEX
  ==================================================
  */

  const currentIndex =
    levels.indexOf(
      currentPracticeLevel
    );


  const assessedIndex =
    levels.indexOf(
      assessedLevel
    );


  /*
  ==================================================
  DOWNGRADE PRACTICE DIFFICULTY
  ==================================================

  Example:

      B1
      42%
      48%
      51%

          ↓

      next practice = A2

  Never move more than one CEFR step.
  ==================================================
  */

  if (
    consistentlyStruggling &&
    weightedScore < 55 &&
    currentIndex > 0
  ) {

    const easierLevel =
      levels[
        currentIndex - 1
      ];


    console.info(
      `Adaptive practice: ${normalizedSkill} reduced from ${currentPracticeLevel} to ${easierLevel} after repeated difficulty.`
    );


    return easierLevel;

  }


  /*
  ==================================================
  MOVE BACK TOWARD ASSESSED LEVEL
  ==================================================

  This is intentionally conservative.

  If practice was lowered from B1 to A2 and
  the learner becomes consistently strong at A2,
  move back toward B1.

  We do NOT automatically exceed the assessed
  level here.
  ==================================================
  */

  if (
    consistentlyStrong &&
    weightedScore >= 85 &&
    currentIndex <
      assessedIndex
  ) {

    const harderLevel =
      levels[
        currentIndex + 1
      ];


    console.info(
      `Adaptive practice: ${normalizedSkill} increased from ${currentPracticeLevel} to ${harderLevel} after strong recent performance.`
    );


    return harderLevel;

  }


  /*
  ==================================================
  KEEP CURRENT LEVEL
  ==================================================
  */

  return currentPracticeLevel;

},


  /*
  ==================================================
  WEAKNESS LOOKUP
  ==================================================
  */

  findWeakness(
    profile,
    concept
  ) {

    const weaknesses =
      profile
        ?.weaknesses;


    if (
      !Array.isArray(
        weaknesses
      )
    ) {

      return null;

    }


    return (

      weaknesses.find(

        weakness =>

          this.normalizeConcept(
            weakness?.concept
          ) ===
          this.normalizeConcept(
            concept
          )

      ) ||

      null

    );

  },


  /*
  ==================================================
  NORMALIZE CONCEPT
  ==================================================
  */

  normalizeConcept(
    value
  ) {

    return String(
      value ||
      ""
    )
      .trim()
      .toLowerCase()
      .replace(
        /\s+/g,
        "_"
      );

  },


  /*
  ==================================================
  FORMAT CONCEPT / SKILL
  ==================================================
  */

  formatConcept(
    concept
  ) {

    return String(
      concept ||
      ""
    )
      .replace(
        /_/g,
        " "
      )
      .replace(
        /\b\w/g,
        character =>
          character
            .toUpperCase()
      );

  },


  /*
  ==================================================
  SESSION ID
  ==================================================
  */

  createSessionId(
    target
  ) {

    return [

      "practice",

      target,

      Date.now()

    ].join(
      "_"
    );

  }

};